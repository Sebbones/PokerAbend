const byId = new Map(MATERIALS.map(item => [item.id, item]));
const sources = new Map();
let instance = 0;
export function getMaterial(id) {
  const item = byId.get(id);
  if (!item) throw new RangeError('Unknown material: ' + id);
  return item;
}
// Inline SVG is intentional: CSS custom properties cannot cross an <img> document boundary.
// Only paths from the fixed catalog are fetched. Caller labels are text, never markup.
export async function createMaterial(id, { label, document = globalThis.document } = {}) {
  const item = getMaterial(id);
  if (!document?.defaultView) throw new Error('createMaterial needs a browser document');
  if (!sources.has(id)) sources.set(id, fetch(new URL(item.file, import.meta.url)).then(response => {
    if (!response.ok) throw new Error('Material unavailable: ' + id);
    return response.text();
  }).catch(error => { sources.delete(id); throw error; }));
  const text = await sources.get(id), parsed = new document.defaultView.DOMParser().parseFromString(text, 'image/svg+xml');
  if (parsed.querySelector('parsererror') || parsed.documentElement.localName !== 'svg') throw new Error('Invalid material SVG: ' + id);
  const svg = document.importNode(parsed.documentElement, true), prefix = `material-${++instance}-`, ids = new Map();
  for (const node of svg.querySelectorAll('[id]')) { const old = node.id; ids.set(old, prefix + old); node.id = prefix + old; }
  for (const node of [svg, ...svg.querySelectorAll('*')]) for (const attribute of [...node.attributes]) {
    let value = attribute.value.replace(/url\(["']?#([^\s)"']+)["']?\)/g, (all, ref) => ids.has(ref) ? `url(#${ids.get(ref)})` : all);
    if (value.startsWith('#') && ids.has(value.slice(1))) value = '#' + ids.get(value.slice(1));
    if (value !== attribute.value) node.setAttribute(attribute.name, value);
  }
  svg.classList.add('material-svg'); svg.dataset.material = item.id;
  svg.setAttribute('role', 'img'); svg.setAttribute('aria-label', label ?? item.name); svg.setAttribute('focusable', 'false');
  const title = svg.querySelector('title'); if (title) title.textContent = label ?? item.name;
  return svg;
}
export async function createAccessory(id, options = {}) {
  if (!getMaterial(id).overlay) throw new TypeError('Material is not an avatar overlay: ' + id);
  const svg = await createMaterial(id, options);
  svg.classList.add('material-accessory'); svg.setAttribute('aria-hidden', 'true');
  return svg;
}
